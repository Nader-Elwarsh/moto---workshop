/* رقم تليفون وهمي: 5 أو 6 أرقام بيبدأ بصفر، وتاني رقم من 3 لـ 9
   (عشان مايشبهش أرقام الموبايل اللي بتبدأ بـ 01 ولا أي شبكة حقيقية) */
export function fakePhone(r = Math.random) {
  const len = r() < .5 ? 5 : 6;
  let s = '0' + (3 + Math.floor(r() * 7));
  while (s.length < len) s += Math.floor(r() * 10);
  return s;
}
